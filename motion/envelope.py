"""Огибающая движения и её пороги.

Четыре починки здесь существуют не для аккуратности, а потому что без каждой
из них замер соврал на настоящем материале. Что именно ломалось — в
docs/superpowers/specs/2026-08-05-motion-analyzer-design.md, п. 2.

Модели фона нет вовсе. Она проваливалась трижды: медиана по времени оказывалась
самим исполнителем, когда он стоял на месте; автоэкспозиция красила кадр
целиком; эрозия назначала палкой торс. Разница соседних кадров ни одного из
этих провалов не имеет.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

FLOOR_PCT = 20.0        # дно — 20-я процентиль
STRIKE_REF_PCT = 95.0   # опора порога удара — 95-я процентиль, НЕ максимум
STRIKE_FRAC = 0.35      # порог удара — дно + 0.35 * (опора - дно)
GUARD_SIGMA = 4.0       # сторож: порог не ниже четырёх сигм дрожания
ACTION_FRAC = 0.50      # уровень действия — половина пути от дна до порога
SIZE_CLIP = 2.0         # во сколько раз рост в кадре может отличаться от медианы
SMOOTH_S = 0.08         # окно сглаживания
LEVEL_FRAC = 0.10       # уровень, по которому мерятся замах и торможение

# Почему опора — процентиль, а не максимум. Настроено на трёх настоящих видео
# по опоре глазом: на v1 в окне 24.5–32.5 с палка движется почти в каждом кадре
# (сверено по контактному листу с шагом 0.25 с). С опорой на максимум замер
# говорит «в действии 1.9%», с опорой на 95-ю процентиль — «87.7%». Максимум
# задаёт возня с камерой у объектива: она в разы сильнее смахов в глубине кадра.
#
# Почему сторож по ДРОЖАНИЮ, а не по низким процентилям. Оценивать шум снизу
# распределения нельзя: в занятом видео нижняя часть — это медленное движение,
# и порог уезжает выше настоящих смахов (на v1 2.12 против нужных 0.98).
# Настоящее движение после сглаживания гладкое, у него соседние отсчёты близки;
# шум — нет. Четыре сигмы, а не шесть: на шести сторож перебивал порог на v3,
# где 30 fps и окно сглаживания вдвое короче.
#
# Порога «три сигмы над покоем» здесь больше нет. Чистого покоя в этом
# материале не существует — исполнитель двигается почти всё время, и любой
# порог, выведенный из «уровня покоя», ложился выше медианы огибающей, то есть
# объявлял покоем больше половины видео по построению.


@dataclass(frozen=True)
class Envelope:
    values: np.ndarray      # сглаженная и нормированная, отсчёт на пару кадров
    times: np.ndarray       # время каждого отсчёта, с
    fps: int
    floor: float            # дно, 20-я процентиль
    noise: float            # сигма дрожания
    action_level: float     # выше этого — действие идёт
    strike_level: float     # выше этого — всплеск ускорения
    scale: float            # на что поделили
    scale_source: str       # "поза" | "разброс" | "нет"
    size_fix: str           # чем починен масштаб внутри видео

    def level_for(self, peak: float) -> float:
        """Уровень 10%, от которого мерятся замах и торможение."""
        return self.floor + LEVEL_FRAC * (peak - self.floor)


def raw_motion(frames: np.ndarray) -> np.ndarray:
    """Разница соседних кадров с подавлением автоэкспозиции.

    Вычитание собственного среднего каждого кадра ДО разницы — вся починка, и
    она одна строка. Без неё скачок экспозиции телефона отличается сразу в
    каждой точке и читается как движение: на настоящем материале он красил в
    маску весь навес, деревья и плитку.
    """
    levelled = frames - frames.mean(axis=(1, 2), keepdims=True)
    return np.abs(np.diff(levelled, axis=0)).mean(axis=(1, 2))


def jitter_sigma(values: np.ndarray) -> float:
    """Шум по дрожанию соседних отсчётов сглаженной огибающей.

    Разность двух независимых отсчётов имеет дисперсию 2*sigma^2, отсюда корень
    из двух; 1.4826 переводит медианное отклонение в сигму. Настоящее движение
    после сглаживания гладкое, у него соседние отсчёты близки; шум — нет.
    """
    values = np.asarray(values, dtype=np.float64)
    if len(values) < 3:
        return 0.0
    return float(np.median(np.abs(np.diff(values)))) * 1.4826 / np.sqrt(2.0)


def smooth(values: np.ndarray, fps: int, window_s: float = SMOOTH_S) -> np.ndarray:
    """Скользящее среднее. Один кадр при 60 fps не бывает замахом.

    Без сглаживания проба выдавала подъём и спад по 0.017 с, то есть по одному
    кадру, — это артефакт спайкового сигнала, а не замер.
    """
    width = max(1, int(round(window_s * fps)))
    values = np.asarray(values, dtype=np.float64)
    if width < 2 or len(values) < width:
        return values
    return np.convolve(values, np.ones(width) / width, mode="same")


def build(frames: np.ndarray, fps: int,
          body_frac: np.ndarray | None = None, t0: float = 0.0) -> Envelope:
    """Огибающая из кадров.

    ВАЖНО: сюда надо подавать УЖЕ обрезанное окно, а t0 — его начало. Пороги
    считаются по тому, что подано, и возня с камерой, если её не отрезать
    заранее, задаёт их сама. На v1 она в пять-восемь раз сильнее настоящих
    смахов: руки у объектива против движения в глубине кадра. Порог уезжал на
    2.99 при смахах 0.7–1.44, и ни один не находился.

    body_frac — рост исполнителя долей высоты кадра, по кадру, из позы. Если
    он есть, чинится ВТОРАЯ беда масштаба: один и тот же смах вблизи и вдалеке
    даёт разную энергию, потому что она растёт как площадь, то есть как
    квадрат роста в кадре. Проба пропустила дальние смахи ровно из-за этого:
    рост в кадре 69 px против 89 у ближних.

    Нормировка на разброс внутри видео чинит ПЕРВУЮ беду — разный контраст
    между съёмками. Это две разные починки, и нужны обе.
    """
    raw = raw_motion(frames)
    if body_frac is not None and len(body_frac) >= len(raw) + 1:
        # Поправка ОТНОСИТЕЛЬНАЯ и ОГРАНИЧЕННАЯ. Первая версия делила на
        # квадрат абсолютного роста с ограничителем 0.05 снизу, и два кадра из
        # 1046 в v1, где поза сорвалась, раздулись в четыреста раз. Максимум
        # огибающей оказался этим артефактом, порог удара уехал в 247 раз выше
        # дна, и настоящие смахи под него не попали.
        #
        # Человек внутри одного дубля не меняет видимый размер больше чем вдвое
        # (в v1 настоящий разброс от 5-й до 95-й процентили — 2.2 раза).
        # Поэтому делим на медиану и зажимаем отношение.
        frac = np.asarray(body_frac, dtype=np.float64)
        median_frac = float(np.median(frac))
        ratio = np.clip(frac / max(median_frac, 1e-6),
                        1.0 / SIZE_CLIP, SIZE_CLIP)
        area = (ratio[:len(raw)] + ratio[1:len(raw) + 1]) / 2.0
        raw = raw / area ** 2
        size_fix = (f"по росту в кадре из позы, поправка зажата в "
                    f"{1 / SIZE_CLIP:g}..{SIZE_CLIP:g} от медианы")
    else:
        size_fix = "нет: позы не было, дальние движения занижены"

    vals = smooth(raw, fps)
    floor = float(np.percentile(vals, FLOOR_PCT))
    active = vals[vals > floor]
    spread = float(active.std()) if active.size > 1 else 0.0
    if spread > 1e-9:
        scale, source = spread, "разброс"
    else:
        scale, source = 1.0, "нет"

    norm = vals / scale
    nfloor = floor / scale
    nnoise = jitter_sigma(norm)
    reference = float(np.percentile(norm, STRIKE_REF_PCT))
    strike_level = max(nfloor + STRIKE_FRAC * (reference - nfloor),
                       nfloor + GUARD_SIGMA * nnoise)
    action_level = nfloor + ACTION_FRAC * (strike_level - nfloor)
    # Отсчёт разницы лежит между своими двумя кадрами, отсюда полкадра.
    times = t0 + np.arange(len(norm)) / fps + 0.5 / fps
    return Envelope(values=norm, times=times, fps=fps, floor=nfloor,
                    noise=nnoise, action_level=action_level,
                    strike_level=strike_level, scale=scale,
                    scale_source=source, size_fix=size_fix)
